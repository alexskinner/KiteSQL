//! The value an identity column last generated on this thread.
//!
//! An INSERT that generates identity values records the first of them here once it has
//! stored its rows; an INSERT that generates none leaves the value alone. Like the
//! diagnostics sink, the value is per thread: a session that runs its statements on one
//! thread sees only its own inserts. Dialects read it for functions such as MySQL's
//! `LAST_INSERT_ID()` and may overwrite it (`LAST_INSERT_ID(expr)`).

use std::cell::Cell;

thread_local! {
    static LAST_GENERATED: Cell<Option<i128>> = const { Cell::new(None) };
}

/// The first identity value generated by the last INSERT on this thread that generated any,
/// or the value last set with [`set_last_generated`]; `None` if there is neither.
pub fn last_generated() -> Option<i128> {
    LAST_GENERATED.with(|c| c.get())
}

/// Replaces the value [`last_generated`] returns.
pub fn set_last_generated(value: Option<i128>) {
    LAST_GENERATED.with(|c| c.set(value));
}

// GRCOV_EXCL_START
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn last_generated_is_per_thread() {
        set_last_generated(Some(7));
        assert_eq!(last_generated(), Some(7));
        std::thread::spawn(|| assert_eq!(last_generated(), None))
            .join()
            .unwrap();
        set_last_generated(None);
        assert_eq!(last_generated(), None);
    }
}
